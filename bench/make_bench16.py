#!/usr/bin/env python3
"""Build BENCH16.COM -- the 16-bit DOS VM half of the UEFI-DOS benchmark.

The same eight workloads are implemented three times (16-bit interpreted DOS,
32-bit native, 64-bit native).  This script generates the 16-bit one and writes
bench/bench_sizes.h so the C versions run exactly the same amount of work.

Every workload is timed with INT 1Ah AH=00h (the 18.2 Hz BIOS tick counter,
which the emulator maintains from wall-clock time in both the host harness and
UEFI), so the reported unit is ticks: multiply by 54925 us for microseconds.
The native builds use RDTSC instead, which is exact.  Every workload is sized so
that a host 16-bit run needs several ticks, except the two I/O workloads, whose
host runs finish below one tick and are therefore only reported from UEFI.
The native builds use RDTSC instead, which is exact.

Workloads:

  alu    N iterations of the 16-bit LCG step x = x*1103 + 12345 (x in a
         register), xor-ed into a checksum
  fill   R passes of STOSB over BENCH_BUF bytes with an incrementing value
  copy   R passes of copying BENCH_HALF bytes byte by byte (MOV/INC/LOOP)
  scan   R passes of summing BENCH_BUF bytes into a 16-bit accumulator
  api    N calls of INT 21h AH=30h (get DOS version), results summed
  text   N single-character console writes through INT 21h AH=02h
  file   create BENCH.DAT, write N bytes in 256-byte blocks, close, reopen,
         read them back, close, delete
  find   R full directory scans of \\BDATA via AH=1Ah/4Eh/4Fh

Output: one line per workload, `BENCH <name> tick=<decimal> cs=<hex>`.

Usage:  python bench/make_bench16.py [output-dir]
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, os.path.join(ROOT, "tools"))

from make_tools import (Asm, call16, data, exit_dos, imm16, int21, jcc16,
                        prolog, puts, putc, putdec_routine)  # noqa: E402

# ---------------------------------------------------------------------------
# Workload sizes.  16-bit loops need a 16-bit counter, hence the inner*outer
# shapes; the C side uses the products from bench_sizes.h.  The sizes are
# chosen so each workload takes about a second in the interpreted DOS world --
# one BIOS tick is 55 ms, so anything much shorter cannot be timed there.
# ---------------------------------------------------------------------------
ALU_OUTER = 40
BENCH_ALU_N = 65536 * ALU_OUTER

BUF = 32768
HALF = 16384
FILL_R = 192
COPY_R = 144
SCAN_R = 96

API_INNER = 16383
API_OUTER = 32
BENCH_API_N = API_INNER * API_OUTER

TEXT_INNER = 16383
TEXT_OUTER = 192
BENCH_TEXT_N = TEXT_INNER * TEXT_OUTER

FILE_N = 132096            # 128 KB + one block (keeps the checksum non-zero)
CHUNK = 1024
FIND_R = 10

SIZES_H = """/* generated by bench/make_bench16.py -- do not edit.
 * bench/bench.c must run exactly the same work as the 16-bit BENCH16.COM that
 * is generated from these same constants. */
#ifndef BENCH_SIZES_H
#define BENCH_SIZES_H
#define BENCH_ALU_N   %(alu)du   /* 16-bit LCG steps */
#define BENCH_BUF     %(buf)du   /* byte buffer */
#define BENCH_HALF    %(half)du  /* copy: source/destination half size */
#define BENCH_FILL_R  %(fill)du  /* fill passes over BENCH_BUF */
#define BENCH_COPY_R  %(copy)du  /* copy passes over BENCH_HALF */
#define BENCH_SCAN_R  %(scan)du  /* sum passes over BENCH_BUF */
#define BENCH_API_N   %(api)du   /* get_version calls */
#define BENCH_TEXT_N  %(text)du  /* single-character console writes */
#define BENCH_FILE_N  %(file)du  /* bytes written then read back */
#define BENCH_CHUNK   %(chunk)du /* write/read block size */
#define BENCH_FIND_R  %(find)du  /* directory scans of \\BDATA */
#endif
""" % dict(alu=BENCH_ALU_N, buf=BUF, half=HALF, fill=FILL_R, copy=COPY_R,
           scan=SCAN_R, api=BENCH_API_N, text=BENCH_TEXT_N, file=FILE_N,
           chunk=CHUNK, find=FIND_R)


# --- instruction emitters (8086 encodings, spelled out) ---------------------
def movw(a, reg, value):
    imm16(a, 0xB8 + reg, value)


def mov_mem_imm(a, name, value):
    a.raw(b'\xC7\x06'); a.addr(name); a.raw(bytes([value & 0xFF, (value >> 8) & 0xFF]))


def mov_abs(a, name, word=True):
    """mov ax,[name] / mov al,[name]"""
    a.raw(b'\xA1' if word else b'\xA0'); a.addr(name)


def store_abs(a, name, word=True):
    """mov [name],ax / mov [name],al"""
    a.raw(b'\xA3' if word else b'\xA2'); a.addr(name)


def mov_store_reg(a, modrm, name):
    """mov [name], r16  (modrm: 0x0E=cx 0x16=dx 0x1E=bx 0x36=si 0x3E=di)"""
    a.raw(bytes([0x89, modrm])); a.addr(name)


def mov_reg_mem(a, modrm, name):
    """mov r16, [name]  -- a LOAD, not an address"""
    a.raw(bytes([0x8B, modrm])); a.addr(name)


def mov_si_addr(a, name):
    """mov si, offset name"""
    a.raw(b'\xBE'); a.addr(name)


def mov_di_addr(a, name):
    """mov di, offset name"""
    a.raw(b'\xBF'); a.addr(name)


def mov_bx_imm(a, value):
    imm16(a, 0xBB, value)


def mov_cx_imm(a, value):
    imm16(a, 0xB9, value)


def mov_dx_str(a, name):
    """mov dx, offset name"""
    a.raw(b'\xBA'); a.addr(name)


# --- timing ----------------------------------------------------------------
def getticks(a):
    """GETTICKS: DX = low word of the 18.2 Hz BIOS tick count (INT 1Ah AH=00h).

    The DOS world has no cycle counter, so this is its clock; the native builds
    use RDTSC.  Clobbers AX, CX, DX.
    """
    a.label('getticks')
    a.raw(b'\xB8\x00\x00')                      # mov ax, 0
    a.raw(b'\xCD\x1A')                          # int 1Ah -> CX:DX = BIOS ticks
    a.raw(b'\xC3')                              # ret


def t_start(a):
    call16(a, 'getticks')
    mov_store_reg(a, 0x16, 't0')                # mov [t0], dx


def t_end(a):
    call16(a, 'getticks')
    a.raw(b'\x2B\x16'); a.addr('t0')            # sub dx, [t0]
    mov_store_reg(a, 0x16, 'dt')                # mov [dt], dx


def report(a, name_label):
    puts(a, name_label)
    mov_abs(a, 'dt')                            # mov ax, [dt]
    call16(a, 'putdec')
    puts(a, 's_cs')
    mov_abs(a, 'csum')
    call16(a, 'puthex16')
    putc(a, 0x0D)
    putc(a, 0x0A)


def puthex16(a):
    """PUTHEX16: print AX as four uppercase hex digits."""
    a.label('puthex16')
    a.raw(b'\x50')                              # push ax
    a.raw(b'\x88\xE0')                          # mov al, ah
    call16(a, 'puthex2')
    a.raw(b'\x58')                              # pop ax
    call16(a, 'puthex2')
    a.raw(b'\xC3')
    a.label('puthex2')
    a.raw(b'\x50')                              # push ax
    for _ in range(4):
        a.raw(b'\xD0\xE8')                      # shr al, 1 (x4)
    a.raw(b'\x24\x0F')                          # and al, 0Fh
    a.raw(b'\x04\x30')                          # add al, '0'
    a.raw(b'\x3C\x3A')                          # cmp al, '9'+1
    a.raw(b'\x72\x02')                          # jb +2
    a.raw(b'\x04\x07')                          # add al, 7
    a.raw(b'\x88\xC2')                          # mov dl, al
    a.raw(b'\xB4\x02')                          # mov ah, 2
    int21(a)
    a.raw(b'\x58')                              # pop ax
    a.raw(b'\x24\x0F')                          # and al, 0Fh
    a.raw(b'\x04\x30')                          # add al, '0'
    a.raw(b'\x3C\x3A')                          # cmp al, '9'+1
    a.raw(b'\x72\x02')                          # jb +2
    a.raw(b'\x04\x07')                          # add al, 7
    a.raw(b'\x88\xC2')                          # mov dl, al
    a.raw(b'\xB4\x02')
    int21(a)
    a.raw(b'\xC3')


# --- workloads -------------------------------------------------------------
def w_alu(a):
    a.label('w_alu')
    t_start(a)
    movw(a, 6, 1)                               # mov si, 1     (x)
    a.raw(b'\x31\xFF')                          # xor di, di    (checksum)
    mov_mem_imm(a, 'outer', ALU_OUTER)
    a.label('alu_outer')
    mov_cx_imm(a, 0)                            # 65536 iterations
    a.label('alu_inner')
    a.raw(b'\x89\xF0')                          # mov ax, si
    mov_bx_imm(a, 1103)
    a.raw(b'\xF7\xE3')                          # mul bx
    a.raw(b'\x05\x39\x30')                      # add ax, 12345
    a.raw(b'\x31\xC7')                          # xor di, ax
    a.raw(b'\x89\xC6')                          # mov si, ax
    a.raw(b'\xE2'); a.rel8('alu_inner')         # loop alu_inner
    a.raw(b'\xFF\x0E'); a.addr('outer')         # dec word [outer]
    jcc16(a, 0x5, 'alu_outer')                  # jnz alu_outer
    a.raw(b'\x31\xF7')                          # xor di, si (fold in the final x)
    mov_store_reg(a, 0x3E, 'csum')              # mov [csum], di
    t_end(a)
    report(a, 'n_alu')
    a.raw(b'\xC3')


def w_fill(a):
    a.label('w_fill')
    t_start(a)
    mov_mem_imm(a, 'outer', FILL_R)
    a.label('fill_outer')
    mov_di_addr(a, 'buf')                       # mov di, offset buf
    a.raw(b'\x30\xC0')                          # xor al, al
    mov_cx_imm(a, BUF)
    a.label('fill_inner')
    a.raw(b'\xAA')                              # stosb
    a.raw(b'\xFE\xC0')                          # inc al
    a.raw(b'\xE2'); a.rel8('fill_inner')
    a.raw(b'\xFF\x0E'); a.addr('outer')
    jcc16(a, 0x5, 'fill_outer')
    mov_abs(a, 'buf', word=False)               # mov al, [buf]
    a.raw(b'\x32\x06'); a.addr('buf_end')       # xor al, [buf_end]
    a.raw(b'\x30\xE4')                          # xor ah, ah
    store_abs(a, 'csum')
    t_end(a)
    report(a, 'n_fill')
    a.raw(b'\xC3')


def w_copy(a):
    a.label('w_copy')
    t_start(a)
    mov_mem_imm(a, 'outer', COPY_R)
    a.label('copy_outer')
    mov_si_addr(a, 'buf')                       # mov si, offset buf
    mov_di_addr(a, 'buf_half')                  # mov di, offset buf+HALF
    mov_cx_imm(a, HALF)
    a.label('copy_inner')
    a.raw(b'\x8A\x04')                          # mov al, [si]
    a.raw(b'\x88\x05')                          # mov [di], al
    a.raw(b'\x46')                              # inc si
    a.raw(b'\x47')                              # inc di
    a.raw(b'\xE2'); a.rel8('copy_inner')
    a.raw(b'\xFF\x0E'); a.addr('outer')
    jcc16(a, 0x5, 'copy_outer')
    mov_abs(a, 'buf_half', word=False)          # mov al, [buf_half]
    a.raw(b'\x32\x06'); a.addr('buf_end')       # xor al, [buf_end]
    a.raw(b'\x30\xE4')                          # xor ah, ah
    store_abs(a, 'csum')
    t_end(a)
    report(a, 'n_copy')
    a.raw(b'\xC3')


def w_scan(a):
    a.label('w_scan')
    t_start(a)
    a.raw(b'\x31\xFF')                          # xor di, di  (sum low)
    a.raw(b'\x31\xED')                          # xor bp, bp  (sum high)
    mov_mem_imm(a, 'outer', SCAN_R)
    a.label('scan_outer')
    mov_si_addr(a, 'buf')                       # mov si, offset buf
    mov_cx_imm(a, BUF)
    a.label('scan_inner')
    a.raw(b'\x8A\x04')                          # mov al, [si]
    a.raw(b'\x30\xE4')                          # xor ah, ah
    a.raw(b'\x01\xC7')                          # add di, ax
    a.raw(b'\x83\xD5\x00')                     # adc bp, 0
    a.raw(b'\x46')                              # inc si
    a.raw(b'\xE2'); a.rel8('scan_inner')
    a.raw(b'\xFF\x0E'); a.addr('outer')
    jcc16(a, 0x5, 'scan_outer')
    a.raw(b'\x31\xEF')                          # xor di, bp (fold the high word in)
    mov_store_reg(a, 0x3E, 'csum')              # mov [csum], di
    t_end(a)
    report(a, 'n_sc')
    a.raw(b'\xC3')


def w_api(a):
    a.label('w_api')
    t_start(a)
    a.raw(b'\x31\xFF')                          # xor di, di
    mov_mem_imm(a, 'outer', API_OUTER)
    a.label('api_outer')
    mov_cx_imm(a, API_INNER)
    a.label('api_inner')
    a.raw(b'\xB4\x30')                          # mov ah, 30h
    int21(a)
    a.raw(b'\x01\xC7')                          # add di, ax
    a.raw(b'\xE2'); a.rel8('api_inner')
    a.raw(b'\xFF\x0E'); a.addr('outer')
    jcc16(a, 0x5, 'api_outer')
    mov_store_reg(a, 0x3E, 'csum')
    t_end(a)
    report(a, 'n_api')
    a.raw(b'\xC3')


def w_text(a):
    a.label('w_text')
    t_start(a)
    mov_mem_imm(a, 'outer', TEXT_OUTER)
    a.label('text_outer')
    mov_cx_imm(a, TEXT_INNER)
    a.label('text_inner')
    a.raw(b'\xB2\x78')                          # mov dl, 'x'
    a.raw(b'\xB4\x02')                          # mov ah, 2
    int21(a)
    a.raw(b'\xE2'); a.rel8('text_inner')
    a.raw(b'\xFF\x0E'); a.addr('outer')
    jcc16(a, 0x5, 'text_outer')
    putc(a, 0x0D)
    putc(a, 0x0A)
    mov_mem_imm(a, 'csum', BENCH_TEXT_N & 0xFFFF)
    t_end(a)
    report(a, 'n_tx')
    a.raw(b'\xC3')


def w_file(a):
    a.label('w_file')
    t_start(a)
    mov_mem_imm(a, 'csum', 0)
    mov_dx_str(a, 'fname')
    mov_cx_imm(a, 0)                            # attribute: normal
    a.raw(b'\xB4\x3C')                          # mov ah, 3Ch (create)
    int21(a)
    jcc16(a, 0x2, 'file_done')                  # jb -> carry: error
    store_abs(a, 'handle')
    mov_mem_imm(a, 'outer', FILE_N // CHUNK)
    a.label('file_w')
    mov_reg_mem(a, 0x1E, 'handle')              # mov bx, [handle]
    mov_cx_imm(a, CHUNK)
    mov_dx_str(a, 'chunk')
    a.raw(b'\xB4\x40')                          # mov ah, 40h (write)
    int21(a)
    a.raw(b'\xFF\x0E'); a.addr('outer')
    jcc16(a, 0x5, 'file_w')
    mov_reg_mem(a, 0x1E, 'handle')
    a.raw(b'\xB4\x3E')                          # mov ah, 3Eh (close)
    int21(a)
    mov_dx_str(a, 'fname')
    imm16(a, 0xB8, 0x3D00)                      # mov ax, 3D00h (open, read)
    int21(a)
    jcc16(a, 0x2, 'file_done')
    store_abs(a, 'handle')
    mov_mem_imm(a, 'outer', FILE_N // CHUNK)
    a.label('file_r')
    mov_reg_mem(a, 0x1E, 'handle')
    mov_cx_imm(a, CHUNK)
    mov_dx_str(a, 'chunk')
    a.raw(b'\xB4\x3F')                          # mov ah, 3Fh (read)
    int21(a)
    a.raw(b'\x01\x06'); a.addr('csum')          # add [csum], ax
    a.raw(b'\xFF\x0E'); a.addr('outer')
    jcc16(a, 0x5, 'file_r')
    mov_reg_mem(a, 0x1E, 'handle')
    a.raw(b'\xB4\x3E')                          # mov ah, 3Eh (close)
    int21(a)
    a.label('file_done')
    mov_dx_str(a, 'fname')
    a.raw(b'\xB4\x41')                          # mov ah, 41h (delete)
    int21(a)
    t_end(a)
    report(a, 'n_fl')
    a.raw(b'\xC3')


def w_find(a):
    a.label('w_find')
    t_start(a)
    a.raw(b'\x31\xFF')                          # xor di, di (entries seen)
    mov_dx_str(a, 'dir_name')
    a.raw(b'\xB4\x3B')                          # mov ah, 3Bh (chdir)
    int21(a)
    mov_mem_imm(a, 'outer', FIND_R)
    a.label('find_outer')
    a.raw(b'\xB4\x1A')                          # mov ah, 1Ah (set DTA)
    mov_dx_str(a, 'dta')
    int21(a)
    mov_dx_str(a, 'pattern')
    mov_cx_imm(a, 0x3F)                         # attribute mask: everything
    a.raw(b'\xB4\x4E')                          # mov ah, 4Eh (find first)
    int21(a)
    jcc16(a, 0x2, 'find_scans')                 # jb -> empty
    a.label('find_next')
    a.raw(b'\x47')                              # inc di
    a.raw(b'\xB4\x4F')                          # mov ah, 4Fh (find next)
    int21(a)
    jcc16(a, 0x3, 'find_next')                  # jae -> more entries
    a.label('find_scans')
    a.raw(b'\xFF\x0E'); a.addr('outer')
    jcc16(a, 0x5, 'find_outer')
    mov_dx_str(a, 'root_name')
    a.raw(b'\xB4\x3B')                          # mov ah, 3Bh (chdir back)
    int21(a)
    mov_store_reg(a, 0x3E, 'csum')              # mov [csum], di
    t_end(a)
    report(a, 'n_fd')
    a.raw(b'\xC3')


# ---------------------------------------------------------------------------
def build():
    a = Asm()
    prolog(a)
    a.raw(b'\x0E\x07')                          # push cs ; pop es (STOS target)
    for name in ('w_alu', 'w_fill', 'w_copy', 'w_scan',
                 'w_api', 'w_text', 'w_file', 'w_find'):
        call16(a, name)
    exit_dos(a, 0)

    getticks(a)
    putdec_routine(a)
    puthex16(a)
    w_alu(a)
    w_fill(a)
    w_copy(a)
    w_scan(a)
    w_api(a)
    w_text(a)
    w_file(a)
    w_find(a)

    # --- data ---------------------------------------------------------------
    # AH=09h prints up to a '$', so every printable string has to end with one
    data(a, 's_cs', b' cs=$')
    for name, text in (('n_alu', b'BENCH alu tick=$'), ('n_fill', b'BENCH fill tick=$'),
                       ('n_copy', b'BENCH copy tick=$'), ('n_sc', b'BENCH scan tick=$'),
                       ('n_api', b'BENCH api tick=$'), ('n_tx', b'BENCH text tick=$'),
                       ('n_fl', b'BENCH file tick=$'), ('n_fd', b'BENCH find tick=$')):
        data(a, name, text)
    data(a, 'fname', b'BENCH.DAT\x00')
    data(a, 'dir_name', b'\\BDATA\x00')
    data(a, 'root_name', b'\\\x00')
    data(a, 'pattern', b'*.*\x00')
    for name in ('t0', 'dt', 'outer', 'csum', 'handle'):
        data(a, name, b'\x00\x00')
    data(a, 'dta', bytes(64))
    data(a, 'chunk', bytes(CHUNK))
    data(a, 'buf', bytes(HALF))                 # buf[0] .. buf[HALF-1]
    data(a, 'buf_half', bytes(HALF - 1))        # buf[HALF] .. buf[BUF-2]
    data(a, 'buf_end', b'\x00')                 # buf[BUF-1]
    return a.finish()


def main():
    outdir = sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, "build")
    os.makedirs(outdir, exist_ok=True)
    code = build()
    path = os.path.join(outdir, "BENCH16.COM")
    with open(path, "wb") as f:
        f.write(code)
    with open(os.path.join(HERE, "bench_sizes.h"), "w", newline="\n") as f:
        f.write(SIZES_H)
    print("wrote %s (%d bytes) and bench/bench_sizes.h" % (path, len(code)))


if __name__ == "__main__":
    main()
